// Regenerates src/renderer/components/agent-logo-paths.ts from
// @lobehub/icons-static-svg (MIT, (c) 2023 LobeHub). Run once per version bump:
//   node scripts/generate-agent-logos.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const VERSION = '1.95.1';
const LOGOS = { claude: 'claude', openai: 'openai', opencode: 'opencode', ollama: 'ollama' };
const target = fileURLToPath(new URL('../src/renderer/components/agent-logo-paths.ts', import.meta.url));
const lines = [];
for (const [id, file] of Object.entries(LOGOS)) {
  const res = await fetch(`https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@${VERSION}/icons/${file}.svg`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  const svg = await res.text();
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]);
  if (paths.length !== 1 || !svg.includes('viewBox="0 0 24 24"') || !svg.includes('fill-rule="evenodd"')) {
    throw new Error(`${file}: unexpected SVG shape`);
  }
  lines.push(`  ${id}: ${JSON.stringify(paths[0])},`);
}
writeFileSync(target, `// Generated by scripts/generate-agent-logos.mjs from @lobehub/icons-static-svg@${VERSION} (MIT).
// Trademarks belong to their owners; logos only identify the respective tool.
import type { AgentLogoId } from '../../shared/agent-profiles';

export const AGENT_LOGO_PATHS: Record<AgentLogoId, string> = {
${lines.join('\n')}
};
`);
console.log(`wrote ${target}`);
